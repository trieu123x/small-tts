"""Bundle the project's Python packages into one Kaggle script kernel.

Kaggle script kernels upload a single file, so the packages are embedded as strings and written to disk at runtime.
Usage: python kaggle/build_kernel.py debug-app
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INCLUDE = ["tts_amis/*.py", "app/*.py"]

RUNTIME = """
import glob, os, shutil, subprocess, sys

SRC = "/kaggle/working/src"
for rel, code in FILES.items():
    path = os.path.join(SRC, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(code)
sys.path.insert(0, SRC)

subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP], check=True)

# CharsiuG2P reads ./vie-n.tsv; use the copy from the data dataset instead of its silent wget.
hits = glob.glob("/kaggle/input/**/metadata.csv", recursive=True)
if not hits:
    sys.exit("metadata.csv not found under /kaggle/input; attach the tts-amis-data dataset")
DATA_DIR = os.path.dirname(hits[0])
os.chdir("/kaggle/working")
shutil.copy(os.path.join(DATA_DIR, "vie-n.tsv"), "vie-n.tsv")
print("DATA_DIR", DATA_DIR, flush=True)
"""


def build(kernel: str) -> Path:
    kernel_dir = ROOT / "kaggle" / kernel
    config = json.loads((kernel_dir / "kernel.json").read_text(encoding="utf-8"))
    include = config.get("include", DEFAULT_INCLUDE)
    files = {
        p.relative_to(ROOT).as_posix(): p.read_text(encoding="utf-8")
        for pattern in include
        for p in sorted(ROOT.glob(pattern))
        if p.is_file() and "__pycache__" not in p.parts
    }
    # Entry code: inline "main" string, or a "main_file" next to kernel.json for anything longer.
    main = config["main"] if "main" in config else (kernel_dir / config["main_file"]).read_text(encoding="utf-8")
    # "defines" become module constants ahead of the entry code, so kernels can share one main_file.
    defines = "\n".join(f"{name} = {json.dumps(value)}" for name, value in config.get("defines", {}).items())
    script = "\n".join(
        [
            f"# Generated by kaggle/build_kernel.py from {', '.join(include)}. Do not edit.",
            f"FILES = {json.dumps(files, ensure_ascii=False, indent=0)}",
            f"PIP = {json.dumps(config['pip'])}",
            RUNTIME,
            defines,
            main,
            "",
        ]
    )
    out = kernel_dir / "build" / config["metadata"]["code_file"]
    out.parent.mkdir(exist_ok=True)
    out.write_text(script, encoding="utf-8")
    (out.parent / "kernel-metadata.json").write_text(
        json.dumps(config["metadata"], ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return out


if __name__ == "__main__":
    print(build(sys.argv[1]))
